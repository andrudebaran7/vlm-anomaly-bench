#!/usr/bin/env python3
"""Write the paper's anchor tables from the committed MVTec AD 2 reports.

    results/tables/anchor_rows.tex           Table 2's body (the paper \\input's it)
    results/tables/anchor_per_condition.tex  per-condition mean ± std over seeds (supplementary)
    results/tables/ablation_rows.tex         Sheet Metal and Fabric under both forward resizes

and print the mean over the usable categories, which Table 2's caption states. The paper repository
copies results/tables/*.tex in with its scripts/pull_results.sh. Nothing here reads a shard: the
reports are the committed record, and every number in the paper must be traceable to one.
"""
import argparse
from pathlib import Path

from vlmab.viz import tables

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--reports", type=Path,
                        default=ROOT / "results" / "mvtec_ad2" / "patchcore_ref_v0.2.21")
    parser.add_argument("--aliased", type=Path,
                        default=ROOT / "results" / "mvtec_ad2" / "patchcore_ref")
    parser.add_argument("--out", type=Path, default=ROOT / "results" / "tables")
    args = parser.parse_args()

    reports = {c: (args.reports / f"{c}.md").read_text() for c in tables.CATEGORY_ORDER}
    source = f"% GENERATED by scripts/make_tables.py from {args.reports.relative_to(ROOT)}/*.md; do not edit.\n"
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "anchor_rows.tex").write_text(source + "\n".join(tables.anchor_rows(reports)) + "\n")
    (args.out / "anchor_per_condition.tex").write_text(
        source + "\n".join(tables.per_condition_rows(reports)) + "\n")
    aliased = {c: (args.aliased / f"{c}.md").read_text() for c in tables.ABLATION_CATEGORIES}
    (args.out / "ablation_rows.tex").write_text(
        f"% GENERATED by scripts/make_tables.py from {args.aliased.relative_to(ROOT)}/ and "
        f"{args.reports.relative_to(ROOT)}/; do not edit.\n"
        + "\n".join(tables.ablation_rows(aliased, reports)) + "\n")
    i, a, b = tables.usable_mean(reports)
    print(f"wrote {args.out.relative_to(ROOT)}/anchor_rows.tex, anchor_per_condition.tex, ablation_rows.tex")
    print(f"mean over the usable categories: I-AUROC {i}, AU-PRO@0.3 {a}, AU-PRO@0.05 {b}")


if __name__ == "__main__":
    main()
