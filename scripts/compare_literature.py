#!/usr/bin/env python3
"""The anchor against other PatchCore results on MVTec AD 2, by category (protocol v0.2.28, post hoc).

A sanity check on the target benchmark, not a gate: the other pipelines differ in split, backbone,
coreset ratio or resolution, so only the category order and the rough level are read. The literature
values are transcribed from the sources named in LITERATURE_SOURCES.

    python scripts/compare_literature.py > results/comparison/patchcore_literature.md
"""
from decimal import Decimal
from pathlib import Path

from scipy.stats import spearmanr

from vlmab.viz import tables

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "results" / "mvtec_ad2" / "patchcore_ref_v0.2.21"
CATEGORIES = ("can", "fabric", "fruit_jelly", "rice", "sheet_metal", "vial", "wallplugs", "walnuts")

LITERATURE_SOURCES = {
    "authors": "MVTec AD 2, arXiv:2503.21622v1, Tables VII and IX: ensemble of three backbones, coreset "
               "0.01%, 256x256, no centre crop, TEST_priv / TEST_priv,mix.",
    "vo": "Vo et al., IEEE Access 2026, Fig. 3: PatchCore-style WRN50-2, 448x448, antialiased, one seed, "
          "TEST_pub, pooled over lighting.",
}
AUTHORS = {  # percent, in CATEGORIES order
    "au_pro_005": {"TEST_priv": (4.7, 11.0, 46.7, 25.6, 15.2, 62.2, 12.8, 51.8),
                   "TEST_priv,mix": (4.6, 12.0, 46.7, 18.5, 13.0, 59.1, 9.9, 44.5)},
    "au_pro_030": {"TEST_priv": (21.6, 34.6, 74.0, 50.9, 39.8, 90.5, 37.4, 81.7),
                   "TEST_priv,mix": (18.1, 35.3, 74.0, 43.1, 34.2, 89.2, 34.8, 77.4)},
}
VO_I_AUROC = (0.541, 0.697, 0.922, 0.603, 0.558, 0.832, 0.624, 0.784)
LIMIT = {"au_pro_005": "AU-PRO@0.05", "au_pro_030": "AU-PRO@0.30"}


def anchor(reports: dict[str, str]) -> dict[str, tuple[Decimal, ...]]:
    """The anchor's three means per category, in CATEGORIES order, as Decimals, as the tables round them."""
    rows = {c: tables.summarise(tables.parse_report(reports[c])) for c in CATEGORIES}
    return {m: tuple(getattr(rows[c], m) for c in CATEGORIES) for m in tables.METRICS}


def rho(a, b) -> float:
    return float(spearmanr([float(x) for x in a], [float(x) for x in b]).statistic)


def report(reports: dict[str, str]) -> str:
    ours = anchor(reports)
    out = ["# The anchor against other PatchCore results on MVTec AD 2", "",
           "Generated by `scripts/compare_literature.py`; protocol v0.2.28, post hoc: the anchor's "
           "values and these literature values were all known before this comparison was written. "
           "A sanity check, not a gate. Anchor: v0.2.21, `test_public`, three seeds.", ""]
    out += [f"- {k}: {v}" for k, v in LITERATURE_SOURCES.items()]
    head = " | ".join(tables.NAMES[c] for c in CATEGORIES)
    for metric, splits in AUTHORS.items():
        pct = [100 * x for x in ours[metric]]
        mean = tables.fmt(sum(pct) / len(pct), 1)
        out += ["", f"## {LIMIT[metric]} (%)", "", f"| Pipeline | {head} | Mean | Spearman with the anchor | Categories with the anchor lower |",
                "|---|" + "---|" * (len(CATEGORIES) + 3),
                f"| Anchor | {' | '.join(tables.fmt(x, 1) for x in pct)} | {mean} | — | — |"]
        for split, values in splits.items():
            lower = sum(float(p) < v for p, v in zip(pct, values))
            out.append(f"| Authors, {split} | {' | '.join(f'{x:.1f}' for x in values)} | "
                       f"{sum(values) / len(values):.1f} | {rho(pct, values):.3f} | {lower} of {len(pct)} |")
    out += ["", "## I-AUROC", "", f"| Pipeline | {head} | Spearman with the anchor |",
            "|---|" + "---|" * (len(CATEGORIES) + 1),
            f"| Anchor | {' | '.join(tables.fmt(x) for x in ours['i_auroc'])} | — |",
            f"| Vo et al. | {' | '.join(f'{x:.3f}' for x in VO_I_AUROC)} | {rho(ours['i_auroc'], VO_I_AUROC):.3f} |"]
    return "\n".join(out) + "\n"


def main() -> None:
    print(report({c: (REPORTS / f"{c}.md").read_text() for c in CATEGORIES}), end="")


if __name__ == "__main__":
    main()
